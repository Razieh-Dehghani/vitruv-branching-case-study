/**
 * Base class for all test implementation classes that handles the initialization of the branching tool and provides useful helper methods.
 */
public abstract class BranchAwareVSUMTestBase {
    protected Path tempDir;

    protected Git git;

    protected UserInteractor userInteractor;
    
    protected InternalVirtualModel innerModel;
    protected BranchManager branchManager;
    protected BranchAwareVirtualModel vsum;

    protected VsumReloadWatcher reloadWatcher;
    protected VsumValidationWatcher validationWatcher;
    protected VsumMergeWatcher mergeWatcher;
    protected VsumPostCommitWatcher postCommitWatcher;

    /**
     * General setup before running the tests.
     * 
     * @throws Exception on JSON file generation error when parsing CAD files
     */
    @BeforeAll
    static void setup() throws Exception {
        // Register resource factory for XMI documents
        Resource.Factory.Registry.INSTANCE.getExtensionToFactoryMap().put("*", new XMIResourceFactoryImpl());

        // Create JSON files for CAD models (if necessary). This may take a very long time!
        CADParser.generateJsonFiles();
    }

    /**
     * Setup of the branching tool and initialization of all fields in the test class. Modified from the tests in Vitruvius-Branching-Test
     * and chapter 3.5.4 in the thesis.
     * 
     * @param tempDir a temporary directory for placing files (use a `@TempDir` annotated `Path` generated by JUnit)
     * @throws Exception on initialization errors
     */
    protected void setupBranching(@TempDir Path tempDir) throws Exception {
        this.tempDir = tempDir;

        // If a Git repository exists (e.g. due to model seeding), open it; else, create a new one
        if (Files.exists(tempDir.resolve(".git"))) {
            git = Git.open(tempDir.toFile());
        } else {
            git = Git.init().setDirectory(tempDir.toFile()).setInitialBranch("main").call();
            git.commit().setMessage("init").setAllowEmpty(true).setAuthor("test", "test@test").call();
        }

        userInteractor = new UserInteractor();

        innerModel = new VirtualModelBuilder()
            .withStorageFolder(tempDir)
            .withUserInteractorForResultProvider(userInteractor)
            .withChangePropagationSpecifications(new Cad2SysmlChangePropagationSpecification(), new Sysml2CadChangePropagationSpecification())
            .buildAndInitialize();
        innerModel.setChangePropagationMode(ChangePropagationMode.TRANSITIVE_CYCLIC);

        branchManager = new BranchManager(tempDir);
        vsum = new BranchAwareVirtualModel(tempDir, innerModel, branchManager);
        branchManager.setPostCheckoutHandler(new PostCheckoutHandler(vsum));

        reloadWatcher = new VsumReloadWatcher(vsum, tempDir);
        validationWatcher = new VsumValidationWatcher(vsum, tempDir);
        mergeWatcher = new VsumMergeWatcher(vsum, tempDir);
        
        postCommitWatcher = new VsumPostCommitWatcher(tempDir);
        postCommitWatcher.attachSemanticChangeTracking(vsum.getChangeBuffer(), vsum::getUuidResolver, vsum::getViewSourceModels);

        reloadWatcher.start();
        validationWatcher.start();
        mergeWatcher.start();
        postCommitWatcher.start();
    }

    /**
     * Cleanup of the branching tool. Copied from the tests in Vitruvius-Branching-Test.
     */
    protected void tearDown() {
        innerModel.dispose();
        vsum.dispose();

        // Stop all background watchers even if the test failed to avoid thread leaks.
        if (validationWatcher != null) validationWatcher.stop();
        if (reloadWatcher != null) reloadWatcher.stop();
        if (mergeWatcher != null) mergeWatcher.stop();
        if (postCommitWatcher != null) postCommitWatcher.stop();
        if (git != null) git.close();
    }

    /**
     * Loads the specified SysML and CAD models and adds the according correspondences between them.
     * 
     * @param sysmlResourcePath the relative file path of the .uml file as seen from the `src/test/resources/sysml/` directory, as specified by the `SysMLParser`
     * @param cadJsonName the name of the corresponding JSON file (without 'json' file extension), as specified by the `CADParser`
     * @throws Exception on model parsing errors
     */
    protected void loadAndConsistModels(String sysmlResourcePath, String cadJsonName) throws Exception {
        // Load SysML and CAD models
        sysml.Model sysmlModel = new SysMLParser(sysmlResourcePath).parse();
        cad.CAD_Model cadModel = new CADParser().parse(cadJsonName);

        // Remove UML packages from the registry; if those packages are present, the `ChangeDtoDeserializer.resolveEClass(String className)`,
        // which is called when performing a merge and searches the EPackage registry for a matching EClass, will try to find an EClass
        // with the same name as the EClass of the given EObject, disregarding the namespace that this objects comes from. In the case of
        // e.g. a 'sysml.Activity', the registry is searched for classes that are named 'Activity'. So, when the UML packages are still in
        // the registry, the `resolveEClass` method may return the EClass of an UML 'Activity', leading to a fatal error while merging.
        EPackage.Registry.INSTANCE.keySet().removeIf(uri -> uri.toLowerCase().contains("http://www.eclipse.org/uml2"));

        // Load correspondence set
        List<String[]> correspondenceSet = new ArrayList<>();

        String[] sysmlModelPath = sysmlResourcePath.split(File.separator);
        String sysmlModelName = sysmlModelPath[sysmlModelPath.length - 2]; // gets the name without '.uml'
        File correspondenceCsv = new File("src/test/resources/correspondence/" + sysmlModelName + "2" + cadJsonName + ".csv");

        if (correspondenceCsv.exists()) {
            Scanner scanner = new Scanner(correspondenceCsv);
            while (scanner.hasNextLine()) {
                String[] elements = scanner.nextLine().split(",");
                correspondenceSet.add(elements);
            }
            scanner.close();
        } else {
            throw new Exception("Correspondences between \"" + sysmlModelName + "\" and \"" + cadJsonName + "\" could not be found");
        }

        // Set user interactor to "no" when asked to create corresponding cad parameters
        userInteractor.setMCSSAnswer(3);

        // Add the SysML model into the VSUM
        modifyView(getSysMLView(), v -> {
            v.registerRoot(sysmlModel, URI.createFileURI(tempDir.toString() + "/sysml.model"));
        });

        // Edit CAD model name and ID
        modifyView(getCADView(), v -> {
            cad.CAD_Model created = v.getRootObjects(cad.CAD_Model.class).iterator().next();
            created.setName(cadModel.getName());
            created.setId(cadModel.getId());
        });

        // Edit created CAD elements
        modifyView(getCADView(), v -> {
            for (cad.Namespace created : v.getRootObjects(cad.CAD_Model.class).iterator().next().getNamespaces()) {
                String correspondingSysmlBlockId = created.getId().substring(0, created.getId().length() - 9);
                String cadId = correspondenceSet.stream()
                    .filter(e -> correspondingSysmlBlockId.equals(e[0]))
                    .findFirst()
                    .get()[1];
                
                cad.Namespace parsed = cadModel.getNamespaces()
                    .stream()
                    .filter(n -> cadId.equals(n.getId()))
                    .findFirst()
                    .get();
                
                created.setName(parsed.getName());
                created.setId(cadId);
                created.getParameters().addAll(parsed.getParameters());
            }
        });

        // Parse remaining CAD elements
        userInteractor.setMCSSAnswer(1); // create corresponding SysML blocks: no (all are already present)

        for (cad.Namespace parsed : cadModel.getNamespaces()) {
            // Skip already inserted namespaces
            if (getCADView().getRootObjects(cad.CAD_Model.class)
                .iterator().next()
                .getNamespaces()
                .stream()
                .map(n -> n.getId())
                .toList()
                .contains(parsed.getId())) continue;

            modifyView(getCADView(), v -> {
                userInteractor.setTextAnswer(""); // from possible previous corresponding namespace insertion

                List<cad.Namespace> createdNamespaces = v.getRootObjects(cad.CAD_Model.class).iterator().next().getNamespaces();

                Optional<String[]> correspondenceEntry = correspondenceSet.stream()
                    .filter(e -> e[1].equals(parsed.getId()))
                    .findFirst();

                if (correspondenceEntry.isPresent()) {
                    // Namespace has a corresponding SysML block
                    userInteractor.setTextAnswer(correspondenceEntry.get()[0]);
                    createdNamespaces.add(EcoreUtil.copy(parsed));
                } else {
                    // Simply insert namespace without any reactions
                    createdNamespaces.add(EcoreUtil.copy(parsed));
                }
            });
        }

        // Make a commit in order to save the loaded models to the file system; otherwise, it would not be possible to create two branches
        // from "main" and commit to them since the second one would not have access to the loaded models and must work with an empty VSUM
        commitAndWaitForChangelog("chore: load and consist models " + sysmlModelName + " and " + cadJsonName, "main");
    }

    /**
     * Identifies and returns the element with the id from the committable view.
     * 
     * @param view a `CommittableView` which should contain the desired element
     * @param id the id of the element
     * @return the found element as an `EObject` OR null if no element with that id was found
     */
    protected EObject findElement(CommittableView view, String id) {
        for (EObject root : view.getRootObjects()) {
            EStructuralFeature rootIdFeature = root.eClass().getEStructuralFeature("id");
            if (rootIdFeature != null && id.equals(root.eGet(rootIdFeature))) return root;

            TreeIterator<EObject> iter = root.eAllContents();

            while (iter.hasNext()) {
                EObject eObject = iter.next();
                
                EStructuralFeature idFeature = eObject.eClass().getEStructuralFeature("id");
                if (idFeature != null && id.equals(eObject.eGet(idFeature))) return eObject;
            }
        }

        return null;
    }

    /**
     * Helper method to get a committable view on a model. Modified from the tests in Vitruvius-Branching-Test.
     * 
     * @param filterFunction a function that checks whether an `EObject` is of the desired type
     * @return a committable view on the internal virtual model
     */
    private CommittableView getView(String viewTypeName, Predicate<? super EObject> filterFunction) {
        var selector = vsum.createSelector(ViewTypeFactory.createIdentityMappingViewType(viewTypeName));
        selector.getSelectableElements().stream().filter(filterFunction).forEach(e -> selector.setSelected(e, true));
        return selector.createView().withChangeRecordingTrait();
    }

    /**
     * Helper method to get a committable view on the entire VSUM.
     * 
     * @return a committable view on the entire VSUM
     */
    protected CommittableView getGlobalView() {
        return getView("global", e -> true);
    }

    /**
     * Helper method to get a committable view on a SysML model.
     * 
     * @return a committable SysML view on the internal virtual model
     */
    protected CommittableView getSysMLView() {
        return getView("sysml", e -> e instanceof sysml.Model);
    }

    /**
     * Helper method to get a committable view on a CAD model.
     * 
     * @return a committable CAD view on the internal virtual model
     */
    protected CommittableView getCADView() {
        return getView("cad", e -> e instanceof cad.CAD_Model);
    }

    /**
     * Helper method to modify a view.
     * 
     * @param view the committable view to modify
     * @param modification the modification to make on the committable view
     */
    protected void modifyView(CommittableView view, Consumer<CommittableView> modification) {
        modification.accept(view);
        view.commitChanges();
    }

    /**
     * Creates a merge engine with the given conflict resolution provider.
     * 
     * @param conflictResolutionProvider the conflict resolution provider to use in the merge engine; must not be `null`
     * @return a new semantic merge engine
     */
    protected SemanticMergeEngine createMergeEngine(ConflictResolutionProvider conflictResolutionProvider) {
        return new SemanticMergeEngine(
            tempDir,
            List.of(new Cad2SysmlChangePropagationSpecification(), new Sysml2CadChangePropagationSpecification()),
            userInteractor,
            conflictResolutionProvider
        );
    }

    /**
     * Helper method to make a commit. Copied from the tests in Vitruvius-Branching-Test.
     * 
     * @param message the commit message
     * @param branch the name of the branch to commit to
     */
    protected void commitAndWaitForChangelog(String message, String branch) throws Exception {
        waitForGitIndexUnlocked(tempDir, 3_000);
        git.add().addFilepattern(".").call();
        git.commit().setMessage(message).setAuthor("test", "test@test").call();
        String sha = git.getRepository().resolve("HEAD").getName();
        new PostCommitTriggerFile(tempDir).createTrigger(sha, branch);
        String relPath = ".vitruvius/changelogs/" + branch + "/json/" + sha.substring(0, 7) + ".json";
        waitForChangelogInObjectStore(tempDir, branch, relPath, 10_000);
        waitForGitIndexUnlocked(tempDir, 3_000);
        git.reset().setMode(org.eclipse.jgit.api.ResetCommand.ResetType.MIXED).setRef("HEAD").call();
    }

    /**
     * Helper method used in making commits. Copied from the tests in Vitruvius-Branching-Test.
     */
    private void waitForChangelogInObjectStore(Path repoRoot, String branchName, String relPath, long timeoutMs) throws InterruptedException, IOException {
        long deadline = java.lang.System.currentTimeMillis() + timeoutMs;
        while (java.lang.System.currentTimeMillis() < deadline) {
            try (
                org.eclipse.jgit.api.Git g = org.eclipse.jgit.api.Git.open(repoRoot.toFile());
                org.eclipse.jgit.revwalk.RevWalk walk = new org.eclipse.jgit.revwalk.RevWalk(g.getRepository())
            ) {
                org.eclipse.jgit.lib.ObjectId head = g.getRepository().resolve("refs/heads/" + branchName);
                if (head != null) {
                    org.eclipse.jgit.revwalk.RevCommit commit = walk.parseCommit(head);
                    try (
                        org.eclipse.jgit.treewalk.TreeWalk tw = org.eclipse.jgit.treewalk.TreeWalk.forPath(g.getRepository(), relPath, commit.getTree())
                    ) {
                        if (tw != null) return;
                    }
                }
            } catch (Exception ignored) {}
            Thread.sleep(100);
        }
    }

    /**
     * Helper method used in making commits. Copied from the tests in Vitruvius-Branching-Test.
     */
    private void waitForGitIndexUnlocked(Path repoRoot, long timeoutMs) throws InterruptedException {
        Path lockFile = repoRoot.resolve(".git/index.lock");
        long deadline = java.lang.System.currentTimeMillis() + timeoutMs;
        int stable = 0;
        while (java.lang.System.currentTimeMillis() < deadline) {
            if (!Files.exists(lockFile)) {
                if (++stable >= 4) return;
            } else {
                stable = 0;
            }
            Thread.sleep(50);
        }
    }
}
